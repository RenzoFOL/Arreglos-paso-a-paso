import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'
function unzip(b:Buffer){const out=new Map<string,Buffer>();let p=0;while(b.readUInt32LE(p)===0x04034b50){const size=b.readUInt32LE(p+18),n=b.readUInt16LE(p+26),extra=b.readUInt16LE(p+28),start=p+30+n+extra;out.set(b.subarray(p+30,p+30+n).toString(),b.subarray(start,start+size));p=start+size}return out}
