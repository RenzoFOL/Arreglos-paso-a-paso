test('ruta contextual, recorrido con pausa y lectura alineada',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Pausar recorrido',exact:true}).click()
 const caption=page.locator('.hero-array-caption p')
 const paused=await caption.textContent()
 await page.waitForTimeout(1800)
 await expect(caption).toHaveText(paused!)
 await page.getByRole('button',{name:'Valor 12 en índice 2',exact:true}).click()
 await expect(caption).toHaveText('Índice 2 → valor 12')
 await page.locator('[data-study-id="route-Ejemplos"]').click()
 await expect(page.locator('[data-study-id="route-Ejemplos"]')).toHaveAttribute('aria-current','step')
 await expect(page.getByRole('button',{name:'Recorrer un arreglo',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Continuar a Laboratorio',exact:true}).click()
 await expect(page.locator('[data-study-id="route-Laboratorio"]')).toHaveAttribute('aria-current','step')
 await expect(page.getByRole('button',{name:'Ejecutar código',exact:true})).toBeEnabled({timeout:30000})
 const layout=await page.locator('[data-study-state^="lab:"] .lab-grid > .panel').evaluateAll(nodes=>nodes.map(node=>{const r=node.getBoundingClientRect();return {top:r.top,height:r.height}}))
 expect(layout).toHaveLength(3)
 for(const box of layout){expect(Math.abs(box.top-layout[0].top)).toBeLessThan(1);expect(Math.abs(box.height-layout[0].height)).toBeLessThan(1)}
 const lineHeight=await page.locator('[data-study-state^="lab:"] .cm-line').first().evaluate(node=>node.getBoundingClientRect().height)
 expect(lineHeight).toBeGreaterThanOrEqual(34)
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.getByRole('navigation').getByRole('button',{name:'Inicio',exact:true}).click()
 await expect(page.getByRole('button',{name:'Reanudar recorrido',exact:true})).toHaveCount(0)
})
test('sesión de evaluación completa y exportación JSON',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Evaluación +'}).click()
 await page.getByLabel(/El participante recibió/).check()
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
 await page.getByRole('button',{name:'Preparar tarea y cerrar panel'}).click()
 await page.locator('[data-study-id="card-Teoría"]').click({position:{x:15,y:15}})
 await page.getByRole('button',{name:/Registrando P01/}).click()
 await page.getByLabel('Resultado del observador').selectOption('A')
 await page.getByRole('button',{name:'Terminar tarea',exact:true}).click()
 await page.getByRole('button',{name:'Finalizar sesión',exact:true}).click()
 const download=page.waitForEvent('download')
 await page.getByRole('button',{name:'Descargar JSON completo'}).click()
 const file=await download
 const fs=await import('node:fs/promises')
 const data=JSON.parse(await fs.readFile((await file.path())!,'utf8'))
 expect(data.tasks[0].result).toBe('A')
 expect(data.tasks[0].start).toBeGreaterThanOrEqual(data.tasks[0].prepared)
 expect(data.events.find((e:any)=>e.type==='first_click').target).toBe('card-Teoría')
 expect(data.events.some((e:any)=>e.type==='navigate'&&e.detail==='Teoría')).toBeTruthy()
 await page.getByRole('button',{name:'Analizar archivos'}).click()
 await page.getByRole('button',{name:'Cargar sesión actual'}).click()
 await expect(page.locator('canvas.heatmap')).toBeVisible()
 const png=page.waitForEvent('download');await page.getByRole('button',{name:'Descargar mapa PNG'}).click();expect((await png).suggestedFilename()).toBe('mapa-clics.png')
})
