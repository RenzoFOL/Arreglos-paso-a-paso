import { test, expect } from '@playwright/test'
test('código y variables largos quedan dentro de paneles; ampliar conserva la ejecución',async({page})=>{
 await page.goto('/')
 await page.locator('[data-study-id="card-Laboratorio"]').click()
 const workspace=page.locator('#lab-workspace')
 const editor=workspace.locator('.console-editor')
 const before=await editor.boundingBox()
 const source=Array(70).fill('# Recorrido de prueba').join('\n')+'\nvalores = [8, 4, 12, 6, 9, 3]\n'+Array.from({length:24},(_,i)=>`copia_${i} = valores.copy()`).join('\n')+'\nprint(valores)'
 await workspace.locator('.cm-content').fill(source)
 await expect(page.getByRole('button',{name:'Ejecutar código',exact:true})).toBeEnabled({timeout:30000})
 await page.getByRole('button',{name:'Ejecutar código',exact:true}).click()
 await expect(page.getByText('Traza lista',{exact:true})).toBeVisible()
 await workspace.locator('input[type=range]').focus()
 await page.keyboard.press('End')
 await expect(workspace.locator('.variable-block')).toHaveCount(25)
 const after=await editor.boundingBox()
 expect(Math.abs(after!.height-before!.height)).toBeLessThan(1)
 const scroll=await workspace.locator('.variables-content').evaluate(node=>({scroll:node.scrollHeight,client:node.clientHeight}))
 expect(scroll.scroll).toBeGreaterThan(scroll.client)
 const line=await workspace.locator('.traced-line').boundingBox()
 const scroller=await workspace.locator('.cm-scroller').boundingBox()
 expect(line!.y).toBeGreaterThanOrEqual(scroller!.y)
 expect(line!.y+line!.height).toBeLessThanOrEqual(scroller!.y+scroller!.height)
 const step=await workspace.locator('.step-pill').textContent()
 await page.getByRole('button',{name:'Ampliar editor a todo el ancho'}).click()
 const boxes=await workspace.locator(':scope > .panel').evaluateAll(nodes=>nodes.map(node=>{const r=node.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom,width:r.width}}))
 expect(boxes[1].y).toBeGreaterThan(boxes[0].bottom)
 expect(boxes[1].y).toBe(boxes[2].y)
 expect(boxes[0].width).toBeGreaterThan(boxes[1].width)
 await expect(workspace.locator('.step-pill')).toHaveText(step!)
 await page.getByRole('button',{name:'Restaurar editor en columnas'}).click()
 await expect(workspace.locator('.step-pill')).toHaveText(step!)
})
